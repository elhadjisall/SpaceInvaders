inline Bitmap font_sheet() { return bitmap(font_px, 5, 7, 65); }

inline Bitmap glyph(int index) {
    Bitmap font = font_sheet();
    Bitmap g = font;
    g.count = 1;
    if (index < 0) index = 0;
    if (index >= font.count) index = 0;
    g.pixels = font.pixels + index * font.width * font.height;
    return g;
}

