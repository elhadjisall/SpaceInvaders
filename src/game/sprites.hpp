inline Bitmap bitmap(const uint8_t* px, int w, int h, int count = 1) {
    Bitmap b;
    b.width = w;
    b.height = h;
    b.count = count;
    b.pixels = px;
    return b;
}

inline Bitmap alien(int frame) {
    switch (frame) {
    case 0: return bitmap(alien0_px, 8, 8);
    case 1: return bitmap(alien1_px, 8, 8);
    case 2: return bitmap(alien2_px, 11, 8);
    case 3: return bitmap(alien3_px, 11, 8);
    case 4: return bitmap(alien4_px, 12, 8);
    case 5: return bitmap(alien5_px, 12, 8);
    default: return bitmap(alien0_px, 8, 8);
    }
}

